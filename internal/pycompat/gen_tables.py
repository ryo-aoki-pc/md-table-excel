"""実行中の Python から Unicode と HTML の Go の表を生成する。"""

import hashlib
import html
import json
from pathlib import Path
import re
import struct
import sys
import unicodedata as ud


ROOT = Path(__file__).resolve().parent
LIMIT = 0x110000
DIGIT = re.compile(r"\d")
SPACE = re.compile(r"\s")
WORD = re.compile(r"\w")


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def facts(cp):
    ch = chr(cp)
    # 語末シグマの前後に置き、Python 自身に Case_Ignorable を判定させる。
    cased = ch.islower() or ch.isupper() or ch.istitle()
    ignorable = ("A" + ch + "Σ").lower().endswith("ς") and (
        " " + ch + "Σ"
    ).lower().endswith("σ")
    flags = (
        int(ch.isspace())
        | (int(ch.isalpha()) << 1)
        | (int(DIGIT.fullmatch(ch) is not None) << 2)
        | (int(WORD.fullmatch(ch) is not None) << 3)
        | (int(cased) << 4)
        | (int(ignorable) << 5)
    )
    assert bool(SPACE.fullmatch(ch)) == ch.isspace()
    decimal = ud.decimal(ch, -1)
    return ud.category(ch), ud.east_asian_width(ch), ud.combining(ch), flags, decimal


def digest_character(digest, cp, values):
    category, width, combining, flags, decimal = values
    digest.update(struct.pack("<IBHb", cp, flags, combining, decimal))
    digest.update((category + width).encode("ascii"))
    digest.update(chr(cp).lower().encode("utf-8"))
    digest.update(b"\0")
    ch = chr(cp)
    # 区切りそのものを含む文字列も衝突しないよう、バイト数を先に記録する。
    def text(value):
        data = value.encode("utf-8")
        digest.update(struct.pack("<I", len(data)))
        digest.update(data)
    for value in (ch.strip(), ch.lstrip(), ch.rstrip(), (ch + "\tX\r" + ch + "\t\n").expandtabs(4)):
        text(value)
    for values in (ch.split(), ch.splitlines(), ch.splitlines(True)):
        digest.update(struct.pack("<I", len(values)))
        for value in values:
            text(value)


def make_ranges(values):
    start = 0
    for cp in range(1, len(values) + 1):
        if cp == len(values) or values[cp] != values[start]:
            yield start, cp - 1, values[start]
            start = cp


def regex_class(points):
    ranges = []
    start = previous = None
    for cp in points + [LIMIT + 1]:
        if start is not None and cp != previous + 1:
            text = r"\x{%x}" % start
            if previous != start:
                text += r"-\x{%x}" % previous
            ranges.append(text)
            start = None
        if start is None:
            start = cp
        previous = cp
    return "".join(ranges)


def main():
    values = []
    lowers = []
    expansions = {}
    sets = {"ReDigit": [], "ReSpace": [], "ReWord": []}
    digest = hashlib.sha256()
    context_digest = hashlib.sha256()
    for cp in range(LIMIT):
        data = facts(cp)
        category, width, combining, flags, decimal = data
        values.append((category, width, combining, flags, decimal - cp if decimal >= 0 else None))
        lower = chr(cp).lower()
        if len(lower) > 1:
            expansions[cp] = lower
            lowers.append(None)
        else:
            delta = ord(lower) - cp
            lowers.append(delta if delta else None)
        for name, flag in (("ReDigit", 4), ("ReSpace", 1), ("ReWord", 8)):
            if flags & flag:
                sets[name].append(cp)
        if not 0xD800 <= cp <= 0xDFFF:
            digest_character(digest, cp, data)
            # Case_Ignorable と Cased の重なりも全コードポイントで確かめる。
            for text in ("AΣ" + chr(cp) + "A", "A" + chr(cp) + "Σ", chr(cp) + "Σ"):
                context_digest.update(text.lower().encode("utf-8") + b"\0")

    lines = [
        "// Code generated by gen_tables.py; DO NOT EDIT.",
        "package pycompat",
        "",
        "// PythonVersion と UnicodeVersion は表を生成した処理系の版。",
        "const PythonVersion = " + quote(sys.version.split()[0]),
        "const UnicodeVersion = " + quote(ud.unidata_version),
        "const pythonIntMaxStrDigits = " + str(sys.get_int_max_str_digits()),
        "",
        "var propertyRanges = []propertyRange{",
    ]
    ranges = list(make_ranges(values))
    for lo, hi, (category, width, combining, flags, offset) in ranges:
        decimal = -1 if offset is None else lo + offset
        lines.append('\t{0x%x, 0x%x, %s, %s, %d, %d, %d},' % (
            lo, hi, quote(category), quote(width), combining, flags, decimal))
    lines += ["}", "", "var lowerRanges = []lowerRange{"]
    for lo, hi, delta in make_ranges(lowers):
        if delta is not None:
            lines.append("\t{0x%x, 0x%x, %d}," % (lo, hi, delta))
    lines += ["}", "", "var lowerExpansions = map[rune]string{"]
    for cp, value in expansions.items():
        lines.append("\t0x%x: %s," % (cp, quote(value)))
    lines += ["}", ""]
    for name, points in sets.items():
        lines.append("// %s は Python の正規表現から生成した文字クラス。" % name)
        lines.append("const %s = %s" % (name, quote(regex_class(points))))
    lines += ["", "var htmlEntities = map[string]string{"]
    for name, value in sorted(html.entities.html5.items()):
        lines.append("\t%s: %s," % (quote(name), quote(value)))
    lines += ["}", "", "var invalidCharrefs = map[int]string{"]
    for cp, value in sorted(html._invalid_charrefs.items()):
        lines.append("\t0x%x: %s," % (cp, quote(value)))
    lines += ["}", ""]
    with (ROOT / "tables_generated.go").open("w", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(lines))
    (ROOT / "testdata").mkdir(exist_ok=True)
    metadata = dict(python=sys.version.split()[0], unicode=ud.unidata_version,
                    characters=LIMIT - 0x800, sha256=digest.hexdigest(),
                    sigma_context_sha256=context_digest.hexdigest())
    with (ROOT / "testdata" / "unicode.json").open("w", encoding="utf-8", newline="\n") as stream:
        json.dump(metadata, stream, ensure_ascii=False, indent=2)
        stream.write("\n")
    print("Unicode: %d 文字、%d 範囲を生成しました" % (metadata["characters"], len(ranges)))


if __name__ == "__main__":
    main()
