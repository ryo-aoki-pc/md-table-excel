func TestFormatNumberPython(t *testing.T) {
	for _, c := range [][2]string{{"-0.0", "0"}, {"-0", "0"}, {"00012", "12"}, {"1.0", "1"}, {"1e20", "1e+20"}, {"1e309", "inf"}, {"-1e309", "-inf"}, {"9007199254740993", "9007199254740993"}} {
		if got := formatNumber(c[0]); got != c[1] {
			t.Errorf("%q => %q, want %q", c[0], got, c[1])
		}
	}
}

