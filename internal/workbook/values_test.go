func TestDateFormatsPython(t *testing.T) {
	cases := []struct {
		format         string
		date, duration bool
	}{
		{"General", false, false},
		{"@", false, false},
		{"_d0", false, false},
		{"\\d0", false, false},
		{"\"days\"0", false, false},
		{"[Red]0", false, false},
		{"[h]:mm:ss", true, true},
		{"[hh]", true, true},
		{"[HH]", false, true},
		{"[m]", true, true},
		{"[s]", true, true},
		{"[hhh]", false, false},
		{"[hhx]", false, false},
		{"\"[h]\"0", false, true},
		{"[h]0;[Red]0", true, true},
		{"0;h", false, false},
		{"[hmm]0", false, false},
		{"[s]0", true, true},
		{"[$-409]m/d/yyyy", true, false},
	}
	for _, c := range cases {
		if isDateFormat(c.format) != c.date || durationFormat.MatchString(c.format) != c.duration {
			t.Errorf("format %q date=%t duration=%t", c.format, isDateFormat(c.format), durationFormat.MatchString(c.format))
		}
	}
}
